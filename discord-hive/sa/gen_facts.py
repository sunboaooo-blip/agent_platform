#!/usr/bin/env python3
"""Generate SA_FACTS.md from the NAS trade_data packets.

Deterministic: every emitted line is read from a packet field. No prose is
invented here. hive-watch.py's responder is given this file and instructed to
assert nothing numeric that is not in it.
"""
import json, hashlib, sys, datetime, os
sys.path.insert(0, os.environ.get('SA_WF_DIR', os.path.expanduser('~/wf')))
from nas import get  # noqa: E402

B = '/ai_pipeline/trade_data/workflow_b'
A = '/ai_pipeline/trade_data/workflow_a'
SA_DIR = os.environ.get('SA_DIR', os.path.expanduser('~/llm-node/hive/sa'))
OUT = os.path.join(SA_DIR, 'SYSTEM.md')

def latest(cad):
    return json.loads(get(f'{B}/{cad}/latest.json'))

def sha(u):
    return hashlib.sha256(get(u)).hexdigest()

L = latest('weekday')
man = json.loads(get(f"{B}/{L['package_path']}/nas_manifest.json"))
di  = json.loads(get(f"{B}/{L['package_path']}/decision_inputs.json"))
ah  = json.loads(get(f"{B}/{L['package_path']}/actual_holdings_by_ticker.json"))
snap= json.loads(get(f"{B}/{L['package_path']}/final_actual_portfolio_snapshot.json"))
scores=[json.loads(x) for x in get(f"{B}/{L['package_path']}/action_scores.jsonl").decode().splitlines() if x.strip()]
epa  = [json.loads(x) for x in get(f"{B}/{L['package_path']}/existing_position_actions.jsonl").decode().splitlines() if x.strip()]
npc  = [json.loads(x) for x in get(f"{B}/{L['package_path']}/new_position_candidates.jsonl").decode().splitlines() if x.strip()]
pc   = json.loads(get(f"{B}/{L['package_path']}/production_research_checks.json"))
aw   = json.loads(get(f'{A}/weekday/latest.json'))
sim  = get(f"{B}/{L['package_path']}/simulated_holdings.csv").decode().splitlines()[1:]

real = {p['contract']['symbol']: float(p['quantity']) for p in snap['positions']}
books = pc['account_allocations'][0]['books']
nonhold = [r for r in scores if r['risk_actions']['sell_action'] != 'HOLD']

PERSONA = open(os.path.join(SA_DIR, 'PERSONA.md'), encoding='utf-8').read()

o=[]
w=o.append
w(PERSONA.rstrip())
w('')
w('# ═══ VERIFIED FACTS ═══')
w('Everything below was read programmatically from the packet named here.')
w('You may cite it. You may not extend, extrapolate, or supply numbers that')
w('are not in it. If a claim you need is absent, say it is absent.')
w('')
w('<!-- GENERATED by sa/gen_facts.py. Do not edit by hand. -->')
w(f'generated_utc: {datetime.datetime.now(datetime.UTC).strftime("%Y-%m-%dT%H:%M:%SZ")}')
w(f'source_packet: {L["run_id"]}  revision {L["revision_id"]}')
w('')
w('## Gate flags (verbatim from the packet)')
w(f'- B execution_authorized = {L["execution_authorized"]}')
w(f'- A optimizer_ready = {aw.get("optimizer_ready")}')
w(f'- A publication_state = {aw.get("publication_state")}; source_status = {aw.get("source_status")}')
w(f'- total is_order_instruction=false count = {sum(1 for r in scores+epa if r.get("is_order_instruction") is False)}')
w(f'- total executable=false count = {sum(1 for r in epa+npc if (r.get("execution_readiness") or {}).get("executable") is False)}')
w(f'- B warning count = {len(L["warnings"])}')
w('')
w('## Verified account facts (final_actual_portfolio_snapshot.json)')
w(f'- snapshot created_at = {snap["created_at"]}')
w(f'- broker = {snap["broker"]}; configured_env = {snap["account_context"]["configured_env"]}')
w(f'- account_context warnings = {snap["account_context"]["warnings"]}')
w(f'- stock positions = {len(real)}; option legs = {len(snap["option_positions"])}; open_orders = {len(snap["open_orders"])}')
w(f'- MAG7 in REAL account: ' + ', '.join(f'{t}={real.get(t,"ABSENT")}' for t in ['AAPL','MSFT','AMZN','GOOGL','GOOG','META','NVDA','TSLA']))
w('')
w('## The three standing defects (reproduce on every packet so far)')
for r in nonhold:
    t=r['ticker']
    w(f'- ONLY non-HOLD score: {t} sell_action={r["risk_actions"]["sell_action"]} '
      f'trigger={r["risk_actions"].get("primary_trigger")} trim={r["risk_actions"].get("suggested_trim_pct")}; '
      f'in real account? {"YES" if t in real else "NO -- ticker absent"}')
w(f'- real-account track portfolio_target_status = "{epa[0].get("portfolio_target_status")}"')
sv=sum(float(l.split(',')[3]) for l in sim)
w(f'- circular NAV: sum(simulated_holdings MV)={sv:.2f}; /stock_bucket_target {di["risk_limits"]["stock_bucket_target"]} '
  f'= {sv/di["risk_limits"]["stock_bucket_target"]:.4f}; decision_inputs.total_value={di["total_value"]:.4f} '
  f'-> {"EXACT (circular)" if abs(sv/di["risk_limits"]["stock_bucket_target"]-di["total_value"])<1e-6 else "differs"}')
w(f'- decision_inputs.portfolio_mode = "{di["portfolio_mode"]}" while cash={di["cash"]:.2f} is derived, not a broker read')
S=snap['assets'][0]['segments']
w(f'- segment double-count: equity_with_loan S={S["S"]["equity_with_loan"]:.2f} F={S["F"]["equity_with_loan"]:.2f} '
  f'identical={S["S"]["equity_with_loan"]==S["F"]["equity_with_loan"]}')
for b in books:
    w(f'- book {b["book_id"]}: nav.status={b["nav"]["status"]} amount={b["nav"]["amount"]} '
      f'eligible_as_denominator={b["nav"]["eligible_as_denominator"]} reconciled={b.get("reconciled")}')
w('')
w('## Tickers named by peers but ABSENT from the Tiger snapshot')
named=['QBTS','RDW','PGY','PARR','DHT','VST','BCS','IAUI','AMD','HPE','WDC']
w('- ' + ', '.join(f'{t}={"present" if t in real else "ABSENT"}' for t in named))
w(f'- SOXX in real account = {real.get("SOXX","ABSENT")} (a "new" SOXX would be an add, not a start)')
w('')
w('## Structured order spec')
w('- NO order-spec schema exists in either contracts/ directory.')
w('- /home/investment/order_drafts and /executed_orders empty since 2026-05-25.')
w('- Required fields before any order can be audited: ticker, side, quantity, '
  'order_type, limit_price, account, expires_at, derived_from(run_id+sha256).')

open(OUT,'w').write('\n'.join(o)+'\n')
print(OUT)
